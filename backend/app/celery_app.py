import os
from celery import Celery

REDIS_URL = os.getenv("REDIS_URL", "redis://redis:6379/0")

celery_app = Celery(
    "pg-mig-webui",
    broker=REDIS_URL,
    backend=REDIS_URL.replace("/0", "/1"),
    include=["app.tasks.migration"],
)

celery_app.conf.update(
    task_serializer="json",
    result_serializer="json",
    accept_content=["json"],
    timezone="UTC",
    enable_utc=True,
)
